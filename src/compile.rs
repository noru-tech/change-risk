//! The policy compiler: one `.change-risk/policy.yml` (with its map), three renderings.
//!
//! * `acc`: the `tiers` and `missing_tier` section of an agent-change-control policy, so the
//!   requirements acc enforces per tier are the ones this policy states.
//! * `requirements`: a tool-neutral document listing, per tier, what the policy requires and which
//!   map patterns route a change there. Data for enforcement (CODEOWNERS, rulesets, approval
//!   rules), not enforcement: `crisk` writes none of those.
//! * `prose`: the policy as Markdown for people and auditors, from a fixed template, so the same
//!   file always renders to the same bytes.

use crate::model::*;
use anyhow::Result;
use serde_json::{Value, json};
use std::collections::BTreeMap;

/// The inputs: the policy and map as read, with their digests.
pub struct Inputs {
    pub policy: Option<Policy>,
    pub policy_digest: Option<String>,
    pub map: Option<Map>,
    pub map_digest: Option<String>,
    /// Where they were read from, for the provenance line (`base revision abc123`, `files`).
    pub origin: String,
}

impl Inputs {
    fn policy(&self) -> Policy {
        self.policy.clone().unwrap_or_else(Policy::builtin)
    }
}

/// The level a map entry routes a change to: the highest level its labels set, if any.
fn entry_level(entry: &MapEntry, policy: &Policy) -> Option<Level> {
    entry
        .labels
        .iter()
        .filter_map(|l| policy.levels.get(l).copied())
        .max()
}

fn yaml_str(s: &str) -> String {
    serde_json::to_string(s).expect("a string serializes")
}

/// acc's `tiers` and `missing_tier`, as YAML. `required_checks` is left out: acc requires checks
/// through its own `checks` block, for every tier.
pub fn acc(inputs: &Inputs) -> String {
    let policy = inputs.policy();
    let mut out = format!(
        "# Generated by crisk compile --to acc from {} ({}). Regenerate rather than edit.\n",
        POLICY_PATH,
        inputs.policy_digest.as_deref().unwrap_or("built-in policy")
    );
    out.push_str("tiers:\n");
    for tier in Tier::ALL {
        let Some(r) = policy.tiers.get(&tier) else {
            continue;
        };
        out.push_str(&format!("  {}:\n", tier.as_str()));
        let mut any = false;
        if let Some(n) = r.min_human_approvals {
            out.push_str(&format!("    min_human_approvals: {n}\n"));
            any = true;
        }
        if let Some(a) = r.agent_review {
            out.push_str(&format!(
                "    agent_review: {}\n",
                match a {
                    AgentReview::Allowed => "allowed",
                    AgentReview::Forbidden => "forbidden",
                }
            ));
            any = true;
        }
        if !r.required_reviewer_teams.is_empty() {
            out.push_str("    required_reviewer_teams:\n");
            for t in &r.required_reviewer_teams {
                out.push_str(&format!("      - {}\n", yaml_str(t)));
            }
            any = true;
        }
        if let Some(d) = r.retroactive_review_within_days {
            out.push_str(&format!("    retroactive_review_within_days: {d}\n"));
            any = true;
        }
        if !any {
            out.push_str("    {}\n");
        }
    }
    if policy.tiers.is_empty() {
        out = out.replace("tiers:\n", "tiers: {}\n");
    }
    out.push_str(&format!("missing_tier: {}\n", policy.missing_tier.as_str()));
    out
}

/// The requirements document.
pub fn requirements(inputs: &Inputs) -> Value {
    let policy = inputs.policy();
    let mut tiers = BTreeMap::new();
    for tier in Tier::ALL {
        let mut protected = Vec::new();
        if let Some(map) = &inputs.map {
            for entry in &map.paths {
                if entry_level(entry, &policy).map(Tier::from_level) == Some(tier) {
                    protected.push(json!({"pattern": entry.pattern, "labels": entry.labels}));
                }
            }
        }
        tiers.insert(
            tier.as_str(),
            json!({
                "requirements": policy.tiers.get(&tier).cloned().unwrap_or_default(),
                "protected_paths": protected,
            }),
        );
    }
    json!({
        "version": VERSION,
        "kind": "change-risk-requirements",
        "policy_digest": inputs.policy_digest,
        "tiers": tiers,
        "emergency": policy.emergency.as_ref().map(|e| json!({
            "label": e.label,
            "declarers": e.declarers,
            "review_within_days": policy.tiers.get(&Tier::Emergency).and_then(|r| r.retroactive_review_within_days),
        })),
        "missing_tier": policy.missing_tier.as_str(),
    })
}

fn cell(s: &str) -> String {
    s.replace('|', "\\|")
}

fn list(items: &[String]) -> String {
    if items.is_empty() {
        "—".into()
    } else {
        items
            .iter()
            .map(|i| format!("`{}`", cell(i)))
            .collect::<Vec<_>>()
            .join(", ")
    }
}

/// The policy as Markdown.
pub fn prose(inputs: &Inputs) -> String {
    let policy = inputs.policy();
    let mut out = String::from("# Change risk policy\n\n");
    out.push_str(&format!(
        "Generated by `crisk compile --to prose` from `{POLICY_PATH}` ({}) and `{MAP_PATH}` ({}), {}. \
         This text is a rendering of those files: change them, not this, and regenerate.\n\n",
        inputs.policy_digest.as_deref().unwrap_or("absent; the built-in policy applies"),
        inputs.map_digest.as_deref().unwrap_or("absent"),
        inputs.origin
    ));

    out.push_str("## How a change is classified\n\n");
    out.push_str(&format!(
        "Every change is assessed from the paths it touches, read against the sensitivity map and \
         this policy as they stand on the target branch, never as the change itself would leave \
         them. A change starts at the **{}** level. Each sensitivity label on a path it touches \
         can raise the level; nothing lowers it. A change to `{CONFIG_DIR}` is always **high**, \
         because it changes the rules every later change is held to. An author may declare a \
         higher risk than the paths imply, never a lower one.\n\n",
        policy.default_level.as_str()
    ));

    out.push_str("## Sensitive areas\n\n");
    match &inputs.map {
        Some(map) if !map.paths.is_empty() => {
            out.push_str("| Paths | Labels | Level |\n| --- | --- | --- |\n");
            for e in &map.paths {
                out.push_str(&format!(
                    "| `{}` | {} | {} |\n",
                    cell(&e.pattern),
                    list(&e.labels),
                    entry_level(e, &policy).map_or("no change", Level::as_str)
                ));
            }
            out.push('\n');
        }
        _ => out.push_str("No paths are mapped to sensitivity labels.\n\n"),
    }
    let signal_levels: Vec<(&String, &Level)> = policy
        .levels
        .iter()
        .filter(|(l, _)| {
            inputs
                .map
                .as_ref()
                .is_none_or(|m| !m.paths.iter().any(|e| e.labels.contains(l)))
        })
        .collect();
    if !signal_levels.is_empty() {
        out.push_str("Labels from other tools' findings set these levels:\n\n");
        for (label, level) in signal_levels {
            out.push_str(&format!("- `{}`: {}\n", cell(label), level.as_str()));
        }
        out.push('\n');
    }

    out.push_str("## Standard changes\n\n");
    if policy.standard_changes.is_empty() {
        out.push_str("There are no pre-approved standard changes.\n\n");
    } else {
        out.push_str(
            "A change is a pre-approved standard change when every path it touches is in one of \
             these entries and nothing raised it above the low level:\n\n",
        );
        for c in &policy.standard_changes {
            out.push_str(&format!("- **{}**: {}\n", cell(&c.name), list(&c.paths)));
        }
        out.push('\n');
    }

    out.push_str("## Emergency changes\n\n");
    match &policy.emergency {
        Some(e) => {
            let days = policy
                .tiers
                .get(&Tier::Emergency)
                .and_then(|r| r.retroactive_review_within_days);
            out.push_str(&format!(
                "An emergency is declared by applying the `{}` label to the change. Only these may \
                 apply it: {}. A label applied by anyone else is ignored. A change cannot declare \
                 itself an emergency in its description.{}\n\n",
                cell(&e.label),
                list(&e.declarers),
                days.map(|d| format!(
                    " An emergency change must be reviewed by someone independent of its author \
                     within {d} day(s) of being merged."
                ))
                .unwrap_or_default()
            ));
        }
        None => out.push_str("This policy defines no emergency path.\n\n"),
    }

    out.push_str("## Requirements by tier\n\n");
    out.push_str("| Tier | Human approvals | Agent review | Reviewer teams | Required checks | Retroactive review |\n| --- | --- | --- | --- | --- | --- |\n");
    for tier in Tier::ALL {
        let r = policy.tiers.get(&tier).cloned().unwrap_or_default();
        out.push_str(&format!(
            "| {} | {} | {} | {} | {} | {} |\n",
            tier.as_str(),
            r.min_human_approvals.map_or("—".into(), |n| n.to_string()),
            r.agent_review.map_or("—", |a| match a {
                AgentReview::Allowed => "allowed",
                AgentReview::Forbidden => "forbidden",
            }),
            list(&r.required_reviewer_teams),
            list(&r.required_checks),
            r.retroactive_review_within_days
                .map_or("—".into(), |d| format!("within {d} day(s)"))
        ));
    }
    out.push_str(&format!(
        "\nA change with no risk assessment is held to the **{}** tier.\n\n",
        policy.missing_tier.as_str()
    ));

    out.push_str("## Changes to this policy\n\n");
    out.push_str(&format!(
        "`{CONFIG_DIR}` is part of the repository. A change to it is assessed under the version \
         already on the target branch, is always high, and takes effect only once merged.\n"
    ));
    out
}

/// Render `inputs` as `target` (`acc`, `requirements` or `prose`).
pub fn render(inputs: &Inputs, target: Target) -> Result<String> {
    Ok(match target {
        Target::Acc => acc(inputs),
        Target::Requirements => crate::canonical::jcs_bytes(&requirements(inputs))?,
        Target::Prose => prose(inputs),
    })
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, clap::ValueEnum)]
pub enum Target {
    /// agent-change-control's `tiers` and `missing_tier` policy section (YAML).
    Acc,
    /// The tool-neutral requirements document (JSON).
    Requirements,
    /// The policy as Markdown, for people and auditors.
    Prose,
}
